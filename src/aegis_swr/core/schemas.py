class ConfidenceLevel(str, Enum):
    """
    Represents confidence levels as an enumeration.

    This class provides an enumeration of different confidence levels to categorize
    a confidence score (e.g., high, medium, low). It also includes a class method
    to determine the confidence level based on a given score.

    :ivar HIGH: High confidence level, represented as the string "high".
    :type HIGH: str
    :ivar MEDIUM: Medium confidence level, represented as the string "medium".
    :type MEDIUM: str
    :ivar LOW: Low confidence level, represented as the string "low".
    :type LOW: str
    """

    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"

    @classmethod
    def from_score(cls, score: float) -> ConfidenceLevel:
        """
        Creates an instance of ConfidenceLevel based on the provided score.

        This method evaluates the given score and categorizes it into one of three
        confidence levels: HIGH, MEDIUM, or LOW. The thresholds for these levels are
        defined as follows:
        - HIGH: score >= 0.80
        - MEDIUM: 0.50 <= score < 0.80
        - LOW: score < 0.50

        :param score: Numeric score that used to determine the confidence level.
        :type score: float
        :return: An instance of the ConfidenceLevel enumeration corresponding to the
            specified confidence level.
        :rtype: ConfidenceLevel
        """
        if score >= 0.80:
            return cls.HIGH
        if score >= 0.50:
            return cls.MEDIUM
        return cls.LOW



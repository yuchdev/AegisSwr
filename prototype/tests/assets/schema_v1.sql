-- schema_v1.sql
-- Reference DDL for the initial crash_history table structure.
-- Apply with: sqlite3 crash_reports.db < schema_v1.sql

CREATE TABLE IF NOT EXISTS crash_history (
    id              TEXT PRIMARY KEY,   -- UUID4 generated by the Orchestrator
    timestamp       TEXT,               -- ISO-8601 UTC string
    dump_name       TEXT,               -- Basename of the .dmp file
    exception_code  TEXT,               -- NTSTATUS code, e.g. 0xc0000005
    faulting_module TEXT,               -- DLL/EXE identified as the crash site
    stack_trace     TEXT,               -- Raw stack trace (max 50 000 chars)
    ai_rca          TEXT,               -- Markdown report from the AI backend
    metadata_json   TEXT                -- JSON blob: {"engine_type":..., "ai_model":...}
);

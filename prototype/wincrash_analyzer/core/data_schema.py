"""Universal Data Schema for crash analysis records"""
from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import TypedDict


class CrashReportEntity(TypedDict):
    """Universal schema for a single crash-analysis record.

    All storage backends consume and produce dictionaries that conform to
    this structure.
    """

    report_id: str       # UUID4 string generated by the Orchestrator
    timestamp: str       # ISO-8601 UTC string
    dump_path: str       # Absolute path to the source .dmp file
    exception_code: str  # NTSTATUS code, e.g. "0xc0000005"
    faulting_module: str # DLL/EXE identified as the crash site
    raw_stack: str | list[str]       # Full un-analysed stack trace text (optionally split by \n)
    ai_analysis: str     # Markdown report returned by the AI backend
    engine_type: str     # "cdb" or "js"
    ai_model: str        # AI model used, e.g. "gemini-1.5-pro"
    dump_size: int | None # Size of the dump file in bytes
    dump_hash: str | None # SHA-256 hash of the dump file
    execution_log: list[dict] | None # Optional logs for the debug engine
    raw_stdout: str | list[str] | None # Optional full output from the debug engine


def make_report_id() -> str:
    """
    Generate a new unique report identifier.

    @return: A UUID4 string.
    """
    return str(uuid.uuid4())


def make_timestamp() -> str:
    """
    Return the current UTC time in ISO-8601 format.

    @return: ISO-8601 UTC string.
    """
    return datetime.now(tz=timezone.utc).isoformat()
